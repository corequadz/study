bool is_allowed(char c)
{
    return (c == 'x' ||
            c == '*' || c == '^' || c == '+' || c == '-' || ('0' <= c && c <= '9'));
}


void coefs(char polynom[], int coef[], int polynom_len)
{
    int cur_coef = 0;
    int cur_pow = 0;
    int coef_pow_fl = 0;
    int sign = 1;
    for (int i = 0; i < polynom_len; i++) {
        char ch = polynom[i];
        if ('0' <= ch && ch <= '9') {
            if (coef_pow_fl == 0) {
                cur_coef = cur_coef * 10 + (ch - '0');
            } else {
                cur_pow = cur_pow * 10 + (ch - '0');
            }
        }

        if (ch == 'x') {
            cur_pow = 1;
            if (cur_coef == 0) {
                cur_coef = 1;
            }
        }

        if (ch == '^') {
            cur_pow = 0;
            coef_pow_fl = 1;
        }

        if (ch == '+' || ch == '-') {
            coef[cur_pow] = sign * cur_coef;
            cur_coef = 0;
            cur_pow = 0;
            coef_pow_fl = 0;
            if (ch == '+') {
                sign = 1;
            } else {
                sign = -1;
            }
        }
    }
    coef[cur_pow] = sign * cur_coef;
}


void print_polynom(int coef[])
{
    bool first = true;
    for (int i = 99; i > -1; i--) {
        int cf = coef[i];
        if (i == 0) {
            if (cf > 0) {
                if (first) {
                    printf("%d", coef[i]);
                    first = false;
                    continue;
                } else if (cf == 1) {
                    printf("+%d", cf);
                } else {
                    printf("+%d", cf);
                }
            } else if (cf < 0) {
                printf("%d", cf);
            }
            continue;
        }
        if (i == 1) {
            if (cf > 0) {
                if (first) {
                    printf("%d*x", coef[i]);
                    first = false;
                    continue;
                } else if (cf == 1) {
                    printf("+x", i);
                } else {
                    printf("+%d*x", cf);
                }
            } else if (cf < 0) {
                if (cf == -1) {
                    printf("-x");
                    continue;
                }
                printf("%d*x", cf);
            }
            continue;
        }
        if (cf > 0) {
            if (first) {
                if (cf == 1) {
                    printf("x^%d", i);
                    first = false;
                    continue;
                } else {
                    printf("%d*x^%d", coef[i], i);
                    first = false;
                    continue;
                }
            } else if (cf == 1) {
                printf("+x^%d", i);
                first = false;
            } else {
                printf("+%d*x^%d", cf, i);
                first = false;
            }
        } else if(cf < 0) {
            if (cf == -1) {
                printf("-x^%d", i);
            } else {
                printf("%dx^%d", cf, i);
            }
            first = false;
        }
    }
    printf("\n");
}


void print_table(int coef[]) {
    for (int i = 99; i > -1; i--) {
        if (coef[i] != 0) {
            if (i != 1 && i != 0) {
                printf("x^%d\t", i);
            } else {
                printf("%d\t", i);
            }
        }
    }
    printf("\n");
    for (int i = 99; i > -1; i--) {
        if (coef[i] != 0) {
            printf("%d\t", coef[i]);
        }
    }
    printf("\n");

}


int enter_polynom(char polynom[])
{
    int polynom_len = 0;
    char ch;
    while (ch != 13) {
        ch = getch();
        if (is_allowed(ch)) {
            printf("%c", ch);
            polynom[polynom_len] = ch;
            polynom_len++;
        }
    }
    printf("\n");
    return polynom_len;
}


void print_graph(int coef[])
{
    int max_pow = 0;
    for (int i = 99; i > -1; i--) {
        if (coef[i] != 0) {
            max_pow = i;
            break;
        }
    }
    int max_coef = coef[max_pow];
    if (max_pow == 1) {
        if (max_coef > 0) {
            linear_up();
        } else {
            linear_down();
        }
    } else if (max_pow % 2 == 0) {
        if (max_coef > 0) {
            parabola_up();
        } else {
            parabola_down();
        }
    } else {
        if (max_coef > 0) {
            parabola_rev_up();
        } else {
            parabola_rev_down();
        }
    }
}


int main()
{
    char polynom[100] = {0};
    int polynom_len = enter_polynom(polynom);
    int coef[100] = {0};
    coefs(polynom, coef, polynom_len);
    print_polynom(coef);
    print_table(coef);
    print_graph(coef);
    return 0;
}
